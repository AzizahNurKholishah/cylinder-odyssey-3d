def _parts(answer_key: str) -> list[tuple[str, str, str | None]]:
    errs = {
        "a": {"a": None, "b": "open_instead_of_closed", "c": "blanket_only", "d": "concept"},
        "b": {"a": "closed_instead_of_open", "b": None, "c": "blanket_only", "d": "concept"},
        "c": {"a": "included_bases", "b": "included_bases", "c": None, "d": "concept"},
    }[answer_key]
    return [(oid, text, errs[oid]) for oid, text, _ in PARTS_OPTIONS_CLOSED]


